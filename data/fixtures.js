// Helper function to get all fixtures as a flat array with division info
export const getAllFixtures = () => {
  const all = [];

  // Premier League
  Object.values(premierLeagueFixtures).forEach((monthFixtures) => {
    monthFixtures.forEach((f) => {
      all.push({ ...f, division: "Premier League" });
    });
  });

  // Division One
  Object.values(divisionOneFixtures).forEach((monthFixtures) => {
    monthFixtures.forEach((f) => {
      all.push({ ...f, division: "Division One" });
    });
  });

  // Women's League
  Object.values(womensLeagueFixtures).forEach((roundFixtures) => {
    roundFixtures.forEach((f) => {
      all.push({ ...f, division: "Women's League" });
    });
  });

  // Division One Playoffs
  Object.values(super4DivOneFixtures).forEach((monthFixtures) => {
    monthFixtures.forEach((f) => {
      all.push({ ...f, division: "Division One Playoffs" });
    });
  });

  // Super Six
  Object.values(superSixFixtures).forEach((monthFixtures) => {
    monthFixtures.forEach((f) => {
      all.push({ ...f, division: "Super Six" });
    });
  });

  // 40 Overs League
  Object.values(fortyOversFixtures).forEach((groupFixtures) => {
    groupFixtures.forEach((f) => {
      all.push({ ...f, division: "40 Overs League" });
    });
  });

  return all;
};

// Helper function to find a fixture by ID
export const getFixtureById = (id) => {
  return getAllFixtures().find((f) => f.id === id) || null;
};

